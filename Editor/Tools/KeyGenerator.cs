using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEditor.AddressableAssets.Settings;

namespace AddrKit.Editor
{
    /// <summary>
    /// Writes a C# file with a constant for every address and label, so typos become compile errors.
    /// "Enemies/Goblin" becomes <c>Keys.Enemies.Goblin</c>; label "level1" becomes <c>Labels.Level1</c>.
    /// </summary>
    public static class KeyGenerator
    {
        static readonly HashSet<string> CSharpKeywords = new HashSet<string>
        {
            "abstract","as","base","bool","break","byte","case","catch","char","checked","class","const","continue",
            "decimal","default","delegate","do","double","else","enum","event","explicit","extern","false","finally",
            "fixed","float","for","foreach","goto","if","implicit","in","int","interface","internal","is","lock","long",
            "namespace","new","null","object","operator","out","override","params","private","protected","public",
            "readonly","ref","return","sbyte","sealed","short","sizeof","stackalloc","static","string","struct","switch",
            "this","throw","true","try","typeof","uint","ulong","unchecked","unsafe","ushort","using","virtual","void",
            "volatile","while"
        };

        /// <summary>While true, Addressables changes do not trigger regeneration (used by test fixtures).</summary>
        public static bool Suspended { get; set; }

        sealed class Node
        {
            public readonly SortedDictionary<string, Node> Children = new SortedDictionary<string, Node>(StringComparer.Ordinal);
            public string Address;   // set when an address ends at this node
        }

        // ---------------------------------------------------------------- pure (unit tested)

        /// <summary>Turns any text into a valid C# identifier.</summary>
        public static string ToIdentifier(string text)
        {
            string id = Regex.Replace(text ?? "", @"[^A-Za-z0-9_]", "_");
            if (id.Length == 0) id = "_";
            if (char.IsDigit(id[0])) id = "_" + id;
            if (CSharpKeywords.Contains(id)) id = "@" + id;
            return id;
        }

        /// <summary>"level-1" or "enemy_boss" becomes "Level1" / "EnemyBoss".</summary>
        public static string ToPascalCase(string text)
        {
            var sb = new StringBuilder();
            bool upperNext = true;
            foreach (char c in text ?? "")
            {
                if (!char.IsLetterOrDigit(c)) { upperNext = true; continue; }
                sb.Append(upperNext ? char.ToUpperInvariant(c) : c);
                upperNext = false;
            }
            return sb.Length == 0 ? text : sb.ToString();
        }

        /// <summary>Builds the full source file text.</summary>
        public static string BuildSource(IEnumerable<string> addresses, IEnumerable<string> labels, string ns)
        {
            var root = new Node();
            foreach (string address in addresses.Where(a => !string.IsNullOrEmpty(a)).Distinct())
            {
                Node node = root;
                foreach (string part in address.Split('/'))
                {
                    if (!node.Children.TryGetValue(part, out Node child))
                        node.Children[part] = child = new Node();
                    node = child;
                }
                node.Address = address;
            }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Written by AddrKit. Do not edit; changes are overwritten.");
            sb.AppendLine("// Regenerate with Tools > AddrKit > Generate Keys.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();

            bool hasNamespace = !string.IsNullOrWhiteSpace(ns);
            int indent = 0;
            if (hasNamespace)
            {
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");
                indent = 1;
            }

            sb.AppendLine(Pad(indent) + "/// <summary>Addressable addresses. Use with Addr.Load, Addr.Spawn and friends.</summary>");
            sb.AppendLine(Pad(indent) + "public static class Keys");
            sb.AppendLine(Pad(indent) + "{");
            WriteChildren(sb, root, "Keys", indent + 1);
            sb.AppendLine(Pad(indent) + "}");
            sb.AppendLine();

            var labelRoot = new Node();
            foreach (string label in labels.Where(l => !string.IsNullOrEmpty(l)).Distinct())
                labelRoot.Children[ToPascalCase(label)] = new Node { Address = label };

            sb.AppendLine(Pad(indent) + "/// <summary>Addressable labels. Use with Addr.LoadAll and Addr.Preload.</summary>");
            sb.AppendLine(Pad(indent) + "public static class Labels");
            sb.AppendLine(Pad(indent) + "{");
            WriteChildren(sb, labelRoot, "Labels", indent + 1);
            sb.AppendLine(Pad(indent) + "}");

            if (hasNamespace) sb.AppendLine("}");
            return sb.ToString();
        }

        static void WriteChildren(StringBuilder sb, Node node, string enclosingName, int indent)
        {
            var used = new HashSet<string> { enclosingName };

            foreach (var pair in node.Children)
            {
                Node child = pair.Value;
                string name = Unique(ToIdentifier(pair.Key), used);

                if (child.Children.Count == 0)
                {
                    sb.AppendLine($"{Pad(indent)}public const string {name} = \"{Escape(child.Address)}\";");
                    continue;
                }

                // An address that is also a folder prefix (e.g. "Hero" and "Hero/Idle"): keep both.
                if (child.Address != null)
                {
                    string selfName = Unique(name + "_", used);
                    sb.AppendLine($"{Pad(indent)}public const string {selfName} = \"{Escape(child.Address)}\";");
                }

                sb.AppendLine($"{Pad(indent)}public static class {name}");
                sb.AppendLine($"{Pad(indent)}{{");
                WriteChildren(sb, child, name, indent + 1);
                sb.AppendLine($"{Pad(indent)}}}");
            }
        }

        static string Unique(string name, HashSet<string> used)
        {
            string candidate = name;
            int i = 2;
            while (!used.Add(candidate)) candidate = name + i++;
            return candidate;
        }

        static string Pad(int level) => new string(' ', level * 4);
        static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

        // ---------------------------------------------------------------- editor integration

        /// <summary>Reads the Addressables data and returns the source that would be written.</summary>
        public static string BuildSourceFromProject(AddressableAssetSettings settings, AddrSettings addr)
        {
            var addresses = AddrEditorUtil.AllEntries(settings).Select(e => e.address);
            var labels = settings.GetLabels().Where(l => l != "default");
            return BuildSource(addresses, labels, addr.keysNamespace);
        }

        /// <summary>Writes the Keys file if its content changed. Returns true when a file was written.</summary>
        public static bool Generate()
        {
            var settings = AddrEditorUtil.AddressablesSettings;
            var addr = AddrEditorUtil.FindAddrSettings();
            if (settings == null || addr == null) return false;

            string source = BuildSourceFromProject(settings, addr);
            string path = addr.keysOutputPath;

            if (File.Exists(path) && File.ReadAllText(path) == source) return false;

            AddrEditorUtil.EnsureFolder(Path.GetDirectoryName(path)?.Replace('\\', '/'));
            File.WriteAllText(path, source);
            AssetDatabase.ImportAsset(path);
            return true;
        }
    }

    /// <summary>Regenerates the Keys file shortly after Addressables entries change.</summary>
    [InitializeOnLoad]
    internal static class KeyAutoGenerate
    {
        static bool pending;

        static KeyAutoGenerate()
        {
            AddressableAssetSettings.OnModificationGlobal += (settings, evt, data) => Schedule();
        }

        static void Schedule()
        {
            if (pending) return;
            pending = true;
            EditorApplication.delayCall += () =>
            {
                pending = false;
                if (KeyGenerator.Suspended || EditorApplication.isPlayingOrWillChangePlaymode || EditorApplication.isCompiling) return;
                var addr = AddrEditorUtil.FindAddrSettings();
                if (addr != null && addr.autoGenerateKeys) KeyGenerator.Generate();
            };
        }
    }
}
